import AppKit
import Foundation

/// Source tag for history rows (system pasteboard vs da transcribuh output).
enum ClipboardItemSource: String, Codable, Equatable {
    case pasteboard
    case transcript
    case screenshot
}

enum ClipboardPayloadKind: String, Codable, Equatable {
    case text
    case image
    case fileURL
}

/// One clipboard history entry. Images live on disk; text/URLs inline in the index.
struct ClipboardItem: Identifiable, Equatable, Codable {
    var id: UUID
    var createdAt: Date
    var kind: ClipboardPayloadKind
    var source: ClipboardItemSource
    /// Plain preview / searchable text (also full body for `.text`).
    var text: String?
    /// Relative filename under the history images folder.
    var imageFileName: String?
    /// Absolute file URLs when kind == `.fileURL`.
    var filePaths: [String]?
    var pinned: Bool
    /// Stable fingerprint for dedupe (content hash).
    var fingerprint: String

    var previewLine: String {
        switch kind {
        case .text:
            let raw = (text ?? "").replacingOccurrences(of: "\n", with: " ")
            return raw.isEmpty ? "(empty text)" : raw
        case .image:
            return source == .screenshot ? "Screenshot" : "Image"
        case .fileURL:
            if let first = filePaths?.first {
                return (first as NSString).lastPathComponent
            }
            return "Files"
        }
    }
}

enum ClipboardPasteboardTypes {
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static func isSensitive(_ board: NSPasteboard) -> Bool {
        let types = board.types ?? []
        return types.contains(concealed) || types.contains(transient) || types.contains(autoGenerated)
    }
}
