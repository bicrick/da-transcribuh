import AppKit
import Foundation

/// Source tag for history rows (system pasteboard vs da transcribuh output).
enum ClipboardItemSource: String, Codable, Equatable {
    case pasteboard
    case transcript
    case screenshot
}

enum ClipboardPayloadKind: String, Codable, Equatable {
    case text
    case image
    case fileURL
}

/// One clipboard history entry. Images live on disk; text/URLs inline in the index.
struct ClipboardItem: Identifiable, Equatable, Codable {
    var id: UUID
    var createdAt: Date
    var kind: ClipboardPayloadKind
    var source: ClipboardItemSource
    /// Plain preview / searchable text (also full body for `.text`).
    var text: String?
    /// Relative filename under the history images folder.
    var imageFileName: String?
    /// Absolute file URLs when kind == `.fileURL`.
    var filePaths: [String]?
    var pinned: Bool
    /// Stable fingerprint for dedupe (content hash).
    var fingerprint: String
    /// Frontmost app name when captured (Maccy `Application:`).
    var applicationName: String?
    var firstCopiedAt: Date
    var lastCopiedAt: Date
    var copyCount: Int
    var imageWidth: Int?
    var imageHeight: Int?

    enum CodingKeys: String, CodingKey {
        case id, createdAt, kind, source, text, imageFileName, filePaths, pinned, fingerprint
        case applicationName, firstCopiedAt, lastCopiedAt, copyCount, imageWidth, imageHeight
    }

    init(
        id: UUID,
        createdAt: Date,
        kind: ClipboardPayloadKind,
        source: ClipboardItemSource,
        text: String?,
        imageFileName: String?,
        filePaths: [String]?,
        pinned: Bool,
        fingerprint: String,
        applicationName: String? = nil,
        firstCopiedAt: Date? = nil,
        lastCopiedAt: Date? = nil,
        copyCount: Int = 1,
        imageWidth: Int? = nil,
        imageHeight: Int? = nil
    ) {
        self.id = id
        self.createdAt = createdAt
        self.kind = kind
        self.source = source
        self.text = text
        self.imageFileName = imageFileName
        self.filePaths = filePaths
        self.pinned = pinned
        self.fingerprint = fingerprint
        self.applicationName = applicationName
        self.firstCopiedAt = firstCopiedAt ?? createdAt
        self.lastCopiedAt = lastCopiedAt ?? createdAt
        self.copyCount = max(1, copyCount)
        self.imageWidth = imageWidth
        self.imageHeight = imageHeight
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(UUID.self, forKey: .id)
        createdAt = try c.decode(Date.self, forKey: .createdAt)
        kind = try c.decode(ClipboardPayloadKind.self, forKey: .kind)
        source = try c.decode(ClipboardItemSource.self, forKey: .source)
        text = try c.decodeIfPresent(String.self, forKey: .text)
        imageFileName = try c.decodeIfPresent(String.self, forKey: .imageFileName)
        filePaths = try c.decodeIfPresent([String].self, forKey: .filePaths)
        pinned = try c.decodeIfPresent(Bool.self, forKey: .pinned) ?? false
        fingerprint = try c.decode(String.self, forKey: .fingerprint)
        applicationName = try c.decodeIfPresent(String.self, forKey: .applicationName)
        firstCopiedAt = try c.decodeIfPresent(Date.self, forKey: .firstCopiedAt) ?? createdAt
        lastCopiedAt = try c.decodeIfPresent(Date.self, forKey: .lastCopiedAt) ?? createdAt
        copyCount = try c.decodeIfPresent(Int.self, forKey: .copyCount) ?? 1
        imageWidth = try c.decodeIfPresent(Int.self, forKey: .imageWidth)
        imageHeight = try c.decodeIfPresent(Int.self, forKey: .imageHeight)
    }

    var previewLine: String {
        switch kind {
        case .text:
            let raw = (text ?? "").replacingOccurrences(of: "\n", with: " ")
            return raw.isEmpty ? "(empty text)" : raw
        case .image:
            return "" // image rows show thumbnail only (Maccy)
        case .fileURL:
            if let first = filePaths?.first {
                return (first as NSString).lastPathComponent
            }
            return "Files"
        }
    }

    var displayApplication: String {
        if let applicationName, !applicationName.isEmpty { return applicationName }
        switch source {
        case .pasteboard: return "Copied"
        case .transcript, .screenshot: return "da transcribuh"
        }
    }
}

enum ClipboardPasteboardTypes {
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static func isSensitive(_ board: NSPasteboard) -> Bool {
        let types = board.types ?? []
        return types.contains(concealed) || types.contains(transient) || types.contains(autoGenerated)
    }
}

enum ClipboardEmptySession {
    /// No meaningful speech and no image payload — do not ingest into history.
    static func shouldSkip(transcript: String?, imagePNG: Data?) -> Bool {
        let hasImage = imagePNG != nil && !(imagePNG?.isEmpty ?? true)
        if hasImage { return false }
        let text = transcript?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        if text.isEmpty { return true }
        // Scrub Whisper non-speech so "[BLANK_AUDIO]" / "No speech" don't become rows.
        return NonSpeechFilter.scrub(text).trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }
}
